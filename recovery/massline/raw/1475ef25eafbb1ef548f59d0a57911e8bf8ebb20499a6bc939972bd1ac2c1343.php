							<div style="overflow: auto; width: 100%;">Art doesn&#039;t need to &quot;involve&quot; (or directly address) political or class issues to reflect them. All art reflects its environs, even that which doesn&#039;t claim any type of &quot;message&quot;.<br /><br />Most of the brash cartoons I watch on Adult Swim, along with the countless sexist and downright nasty humor pages I read online actually satirize the socioeconomic factors that cause racial, class and gender inequalities here in the United States (take Kevin Smith&#039;s work, as a prime example). So while they might appear crude, slapstick and otherwise &quot;offensive&quot;, they all reflect the clashes that go on daily within this society. Certain art (and yes, pornography counts here) might even take a regressive stance and openly promote degrading women or some other &quot;counter-revolutionary&quot; shit, but it still mirrors the relationship paradigms we deal with on a constant basis as chains and cogs of a system that naturally pits human beings against each other.<br /><br />So to answer your question, art doesn&#039;t need to &quot;speak&quot; pro or against any political or economic issues when it already reflects the social factors that influence the artist.</div>
