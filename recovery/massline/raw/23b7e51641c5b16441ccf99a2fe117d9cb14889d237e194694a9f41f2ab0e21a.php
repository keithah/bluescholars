							<div style="overflow: auto; width: 100%;">Dear aekae – I’m sure you’d like to think that my singular comment directed toward you yesterday was infused with deep-seeded emotion and intended to do damage, but in fact, it was less the E-quivalent of schoolyard bullying and more like sticking out my tongue and making fart noises.&nbsp; Furthermore, it was neither unprovoked nor undeserved.<br /><br />How are you really gonna say you were just minding your own business when you’ve been thoroughly minding mine for months?&nbsp; &nbsp;You go at me relentlessly for no apparent reason and, unbeknownst to you, I think it’s funny.&nbsp; Just like I think Type is funny (curt rambis goggles = priceless!), and suge and locash, and just like I thought POS was funny... up to a certain point.&nbsp; <br /><br />You have many misconceptions about me, the most outrageous being that I am bereft of a sense of humor.&nbsp; I have no problem laughing at myself, whether it’s the ridiculous beard, my involvement with the temple of hiphop or writing campy rap songs about “cultural preservation.”&nbsp; Trust me; I see the comedic value in all of it, but when the same jokes are retold for years they kinda stop being funny -- most especially when they’re no longer relevant&nbsp; (the amish beard is gone, there IS no temple, and I haven’t written an “ode to hiphop” in years!) – it’s like clowning common for wearing crocheted pants in ’07…&nbsp; you see where I’m going with this?<br /><br />So, back to the comment about you posing for the flyer; in all honesty, was that disrespectful or inappropriate?&nbsp; Did I really compromise my position on gender equality and undo all of gabe’s [love]work related to breaking down the walls of this patriarchal system by suggesting you were, uh, what – thin and dressed in fishnets?!?&nbsp; I never once used the words “crack,” “whore,” “skank,” “slut,” or “aurora;” that would have been crossing the line.&nbsp; &nbsp;It was a joke – the type I would have expected you to appreciate based on the diatribes I get from larry about “I roll with people who have been outside and know about life and get jokes and blah blah blah…”&nbsp; it was the same kind of humor I used when I wrote the piece about boycotting the capitol hill times (c’mon – that shit was a riot!!).&nbsp; it was the type of humor I presumed you employed when callin’ ME out by name on the proof, but if I’m wRAng, and there’s something more to it, by all means, lemme know and we can sort it out.&nbsp; After all, you know there’s no community without UNITY!<br /><br /><img src="http://i29.photobucket.com/albums/c271/SCIONtificrecords/deaddaisies.jpg" alt="" border="0" /><br /></div>
