 began following the Darryl Hunt case in 1994, and ten years of research and interviews went into the making of The Trials of Darryl Hunt, a documentary following his long and painful road to eventual justice. Produced for the premium cable network HBO, The Trials of Darryl Hunt was screened to enthusiastic reviews at the 2006 Sundance Film Festival.<br /><br />for questions or more info: <br />filmseriesinfo@gmail.com</div>
