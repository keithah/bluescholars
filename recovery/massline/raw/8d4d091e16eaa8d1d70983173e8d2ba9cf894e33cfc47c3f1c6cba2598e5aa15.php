							<div style="overflow: auto; width: 100%;">I have some strange info for you related to your scene.<br /><br />Yesterday as I was finalizing the booking our Staxxtoberfest III concert at Columbia City Theatre this October 27th - we almost lost our show. For some reason that was obviously related to your group&#039;s activism, the police pulled the manager of the theatre aside. The Seattle Police Dept said they don&#039;t want any underground hip hop at the club (and who knows where else), because they claim that the music and the scene is a source of trouble. DJ Fresh and I were stunned because we thought he meant faux-thug pop rap. The other side of the golden coin of the Hip Hop that glorifies aggression for record sales, rather than aggressively being active in your community. We even mentioned Mass Line, and what you are doing in the community. . .it was just dumbfounding.<br /><br />We worked it out, or at least got around it - but we definitely felt the repercussions of the incident with DV One. Our DJ had even worked with DV ONE before on tour and mentioned how shocked and saddened he was about what happened. He knew the score and he thought the world of him as a musician and as a person.<br /><br />I was even at the Theatre for the supposed Hip Hop incident that got the Theatre the ire of the Police. In reality it was a shakedown because there was no incident; just a push and a shove; then some words and cooler heads prevailing. Unfortunate as it was, it was rather enchanting to see such actions not lead to violence. There was just a disagreement between a patron and a member of the staff who had a good point to make, and a call for respect.<br /><br />Something was certainly rotten in South Seattle. I thought it was pretty low to silence the music for politics. That very evening your organization (as I understand it) was actively signing up patrons to vote, and I comped them some tickets encouraging them to be part of our upcoming event.<br /><br />Just a heads up from the front lines<br /><br />Davin Michael Stedman<br />aka DP Staxx<br />Soul United Productions </div>
