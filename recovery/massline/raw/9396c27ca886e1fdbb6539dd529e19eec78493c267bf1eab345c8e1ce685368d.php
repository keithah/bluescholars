-back &quot;Proud to Be a Stoner&quot; sounds like it was found stuck between the seats of a 1972 hippie van. If there&#039;s any reason to worry about this mellowing, it&#039;s that sometimes the production sounds too button-up for the punk and rock-rap numbers, although &quot;Loadies&quot; gets it just right thanks to some gutsy fuzz guitar. A few fans might fall off, a few fans might jump on because of the group&#039;s ever-growing love of chillin&#039; and sunshine, but this otherwise straight-up-the-middle Kings album won&#039;t surprise or sway most. ~ David Jeffries, All Music Guide<br /></div>
