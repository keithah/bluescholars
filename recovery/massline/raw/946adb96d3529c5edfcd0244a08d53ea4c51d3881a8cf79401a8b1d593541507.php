eople. <br /><br /><b>Advocacy continues as a theme with a story by KIRO 7’s Monique Ming Laven about Blue Scholars, a hip hop duo that promotes social consciousness rather than perpetuating the reputation that this genre is all about hate and violence. Its latest track, Back Home, demands a withdrawal from Iraq by highlighting the sacrifices military families make. <br /><br />The Blue Scholars are unique in another way. While much of Seattle’s burgeoning hip hop scene consists of African American artists, MC Geologic is Filipino American and DJ Sabzi is Iranian American. The blending of their experiences infuses their music with a primarily immigrant perspective. Their newest CD is titled Bayani, a word fusing Farsi and Tagalog that translates to &quot;voice of the people.&quot; </b><br /><br />InColor is an Emmy-award winning quarterly magazine program that examines diversity in the Pacific Northwest, the issues it raises and its impact on all <br /><br /></td>
