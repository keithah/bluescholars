							<td height="50" colspan="3" valign="top" class="windowbg2" align="left">What’s Up Everyone, <br /><br />A BIG thanks to everyone who came out to support Make It or Break It 3. <br />We are proud to say that it was a very successful event. <br />This event was designed to support &amp; educate local up-n-coming Northwest artists by providing an opportunity to learn a few tricks of the trade, gain experience in what’s expected of them from a promoters perspective (ie: communication, professionalism, QUALITY and execution). This time around we thought it would be a nice touch to bring aboard various RESPECTED members of the hip-hop community to provide each artist with HONEST and valuable feedback about their performance to further their development.<br />The “judges” (for lack of a better description) represent every aspect of the music industry from talent buyers, promoters, journalists, media, artist management, respected performers and most of all, the fan!<br />The feedback (from the judges) was intended FOR THE ARTIST and the artist only!<br />C O N F I D E N T I A L. <br />The ONLY people who had access to the actual feedback were 2 members of Obese and the artists themselves. So to make any sort of suggestion that anyone aside from those individuals are aware of the content provided in the feedback, is mere speculation.<br />If the judges decided to share feedback amongst themselves, that’s one thing.<br />But needless to say we at Obese are little disappointed that the judges would make this a public debate. <br />THERE ARE STILL A COUPLE OF ARTISTS WHO HAVE YET TO RECEIVE THEIR FEEDBACK. That’s because we have chosen to sit individually with each participant. And unfortunately this public debate has possibly damaged or decreased the value of what the judges had to say.<br />We encourage the participants (artists) of Make It or Break It 3 to share their experiences and opinions, especially in regards to the feedback received.<br />Was it too harsh? Was it helpful? Did you appreciate the different perspectives?<br /><br />Thanks again EVERYONE for your support.<br />If you have any questions or interest about future Make it or Break it events please contact us: <a href="mailto:info@obeseproductions.com">info@obeseproductions.com</a><br /><br />xoxo,<br />Obese Productions . com</td>
