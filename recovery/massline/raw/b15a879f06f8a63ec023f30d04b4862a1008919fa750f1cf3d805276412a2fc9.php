							<div style="overflow: auto; width: 100%;">Backpacker was originally a term for somebody that was really deep into hip hop.  It came around in the early to mid-90s.  It was also generally an East coast term.  It was used because a lot of MCs used mass transit since they didn&#039;t own their own rides, and therefore they always had a backpack to carry around their rhyme book(s) and any product they had to sell.  They were also frequently assumed to have dope skills. Backpackers, being from the East coast (yeah, yeah, I know not everybody was East coast, but that&#039;s where it originates), were usually very critical of West Coast music, and anything in general that didn&#039;t have that East coast grimey sound to some degree.  In the late &#039;90s some folks started turning this on its head.  As hip hop gained popularity and a lot of folks started listening to more hip hop on the radio that was often dumbed down, these same Backpackers, around the country, would often attack &quot;mainstream&quot; or &quot;commercial&quot; hip hop as garbage.  So, a lot of folks started using backpacker as a dis, since those cats attacked their music, folks started attacking back.  So, then East coast flavored music with complicated flows and abstract or philosophically minded artists started being labeled backpack in a negative way, by those who prefered other styles of hip hop.  Backpack has since evolved to imply a narrow, elitist, self-important attitude and perspective on hip hop.</div>
