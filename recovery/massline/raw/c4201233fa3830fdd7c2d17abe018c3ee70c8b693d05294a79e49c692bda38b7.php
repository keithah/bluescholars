					<div style="margin: 0 5ex;">I&#039;ve had a few emails asking me about CMJ and radio so thought I&#039;d just share the info with everyone.<br /><br />Radio is a great tool - non-commercial stations like KEXP are key to promoting your album. Satellite and web radio are also becoming increasingly important.&nbsp; The non-commercial stations and college stations report to a chart called CMJ - also a monthly magazine -www.cmj.com (http://www.cmj.com). But of course getting all the stations to play your album is difficult, so there are companies you can hire that do it for you. They mail out your albums to all the stations, have relationships with the music directors and important dj&#039;s for your genre of music, and give you reports and feedback. They will also hook up promotion and interviews at the stations when you tour. For Massline, we&#039;ve been using Terrorbird - http://www.terrorbird.com/ who have been doing an amazing job. Highly recommended to anyone releasing a hip hop album. They also have a great service that send out digital EPs to radio, which saves on the cost of mailing the cds. <br /><br />It costs about $3,000 to really work an album to the whole CMJ panel, so you have to make sure it&#039;s going to be effective for your release. That means that if you get radio support in a market you need to follow it up by getting albums into stores, playing shows in that market, getting press, doing street marketing, etc. <br /><br />as always, if you have any questions about working your album, distribution, etc, let me know.</div>
