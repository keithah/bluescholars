							<div style="overflow: auto; width: 100%;">Our moods move like the tides sometimes.&nbsp; One minute we are close to the world... the next we are withdrawn.&nbsp; I would say the same goes with our interest.&nbsp; &nbsp;One day we are devoting ourselves to one endeavor, and not a week later it&#039;s something else.&nbsp; And in some cases someone else.<br /><br />This leads me to ask this question:&nbsp; What is it that we are really looking for?&nbsp; Could it be entertainment?&nbsp; Could it be Love?&nbsp; Or maybe we simply seek to fulfill our desire for pleasure and we just tend to gravitate to what ever circumstance fills us.<br /><br />Should the latter of these be the case, what happens when the interest fades?&nbsp; Do we forget the pleasure it once gave us?&nbsp; Do those certain people we fancy stop making us smile?&nbsp; Or is it something that is more inside of ourselves?&nbsp; Is it that we decide to stop smiling.&nbsp; Is it we who decide to cast aside our longing for certain pleasures that we for just one moment are no longer concerned with what we abtained our pleasure from?<br /><br />It&#039;s something to ponder.<br /></div>
